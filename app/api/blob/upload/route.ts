
import { NextResponse } from "next/server";
import { issueSignedToken } from "@vercel/blob";
import {
  handleUploadPresigned,
  type HandleUploadPresignedBody,
} from "@vercel/blob/client";
import { getAdminSession } from "@/lib/auth";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

// ==========================================
// BLOB CONFIGURATION
// ==========================================

const allowedContentTypes = [
  "image/jpeg",
  "image/png",
  "image/webp",
  "image/avif",
];

const maxSize = 15 * 1024 * 1024;

const tokenLifetime = 15 * 60 * 1000;
const uploadUrlLifetime = 10 * 60 * 1000;

// ==========================================
// POST
// ==========================================

export async function POST(request: Request) {
  try {
    // ========================================
    // 1. READ STORE CONFIGURATION
    // ========================================

    // Exact environment variable names
    // generated by your Vercel Blob connection.

    const storeId =
      process.env.BLOB_READ_WRITE_TOKEN_STORE_ID?.trim();

    const webhookPublicKey =
      process.env.BLOB_READ_WRITE_TOKEN_WEBHOOK_PUBLIC_KEY?.trim();

    console.log("[BLOB CONFIG]", {
      hasStoreId: Boolean(storeId),
      hasWebhookPublicKey: Boolean(webhookPublicKey),
      hasOidcToken: Boolean(process.env.VERCEL_OIDC_TOKEN),
      hasReadWriteToken: Boolean(process.env.BLOB_READ_WRITE_TOKEN),
      environment: process.env.VERCEL_ENV || "unknown",
    });

    if (!storeId) {
      return NextResponse.json(
        {
          success: false,
          error: "BLOB_READ_WRITE_TOKEN_STORE_ID is missing.",
        },
        { status: 500 }
      );
    }

    if (!webhookPublicKey) {
      return NextResponse.json(
        {
          success: false,
          error: "BLOB_READ_WRITE_TOKEN_WEBHOOK_PUBLIC_KEY is missing.",
        },
        { status: 500 }
      );
    }

    // ========================================
    // 2. READ REQUEST BODY
    // ========================================

    let body: HandleUploadPresignedBody;

    try {
      body = (await request.json()) as HandleUploadPresignedBody;
    } catch {
      return NextResponse.json(
        {
          success: false,
          error: "Invalid upload request body.",
        },
        { status: 400 }
      );
    }

    // ========================================
    // 3. HANDLE PRESIGNED UPLOAD
    // ========================================

    const result = await handleUploadPresigned({
      body,
      request,

      webhookPublicKey,

      // ======================================
      // 4. GENERATE SIGNED UPLOAD TOKEN
      // ======================================

      getSignedToken: async (pathname) => {

        // ADMIN AUTHENTICATION
        const session = await getAdminSession();

        if (!session) {
          throw new Error("Unauthorized");
        }

        // ====================================
        // PATH VALIDATION
        // ====================================

        const validPath =
          /^products\/(tour|train|flight|bus|accommodation|visa)\/[1-9]\d*\/[a-zA-Z0-9][a-zA-Z0-9._-]*$/.test(
            pathname
          );

        if (!validPath) {
          throw new Error("Invalid upload pathname");
        }

        console.log("[BLOB] Generating signed token:", {
          pathname,
          storeIdConfigured: Boolean(storeId),
        });

        // ====================================
        // SIGN TOKEN FOR THE CORRECT STORE
        // ====================================

        const token = await issueSignedToken({
          pathname,

          operations: ["put"],

          allowedContentTypes,

          maximumSizeInBytes: maxSize,

          validUntil: Date.now() + tokenLifetime,

          // IMPORTANT:
          // Use the exact Store ID variable
          // generated by your Vercel dashboard.

          storeId,
        });

        console.log("[BLOB] Signed token created:", {
          pathname,
          success: true,
        });

        // ====================================
        // 5. RETURN UPLOAD URL OPTIONS
        // ====================================

        return {
          token,

          urlOptions: {
            allowedContentTypes,

            maximumSizeInBytes: maxSize,

            validUntil: Date.now() + uploadUrlLifetime,

            addRandomSuffix: true,

            allowOverwrite: false,
          },
        };
      },

      // ======================================
      // 6. UPLOAD COMPLETED
      // ======================================

      onUploadCompleted: async ({ blob }) => {
        console.log("[BLOB] UPLOAD COMPLETED:", {
          pathname: blob.pathname,
          url: blob.url,
          contentType: blob.contentType,
        });
      },
    });

    // ========================================
    // 7. SUCCESS RESPONSE
    // ========================================

    console.log("[BLOB] PRESIGNED RESPONSE SUCCESS");

    return NextResponse.json(result);

  } catch (error) {

    // ========================================
    // 8. ERROR HANDLING
    // ========================================

    const message =
      error instanceof Error
        ? error.message
        : String(error);

    console.error("[BLOB UPLOAD ERROR]", {
      message,
      error,
    });

    const status =
      message === "Unauthorized"
        ? 401
        : message === "Invalid upload pathname"
          ? 400
          : 500;

    return NextResponse.json(
      {
        success: false,
        error: message,
      },
      { status }
    );
  }
}
